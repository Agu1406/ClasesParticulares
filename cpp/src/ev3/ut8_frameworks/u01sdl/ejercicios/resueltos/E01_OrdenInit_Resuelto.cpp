#include <iostream>
using namespace std;

void ImprimirMenu()
{
    cout << "=== EJERCICIO ===" << endl;
    cout << "1. Ejecutar solucion" << endl;
    cout << "2. Ver objetivo" << endl;
    cout << "0. Salir" << endl;
}

void EjecutarEjercicio()
{
    cout << "SDL_Init" << endl;
    cout << "SDL_CreateWindow" << endl;
    cout << "SDL_CreateRenderer" << endl;
    cout << "SDL_DestroyRenderer" << endl;
    cout << "SDL_DestroyWindow" << endl;
    cout << "SDL_Quit" << endl;
}

int main()
{
    int opcion;
    do
    {
        ImprimirMenu();
        cout << "Introduce una opcion -> ";
        cin >> opcion;
        cout << endl;
        switch (opcion)
        {
            case 1:
                EjecutarEjercicio();
                break;
            case 2:
                cout << "Orden Init -> Window -> Renderer -> Destroy -> Quit." << endl;
                break;
            case 0:
                cout << "Saliendo..." << endl;
                break;
            default:
                cout << "Opcion no valida." << endl;
                break;
        }
        cout << endl;
    } while (opcion != 0);
    return 0;
}
