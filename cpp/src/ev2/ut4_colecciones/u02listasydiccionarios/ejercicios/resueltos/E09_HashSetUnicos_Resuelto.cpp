#include <iostream>
#include <set>
using namespace std;

void ImprimirMenu()
{
    cout << "=== EJERCICIO ===" << endl;
    cout << "1. Ejecutar solucion" << endl;
    cout << "2. Ver objetivo" << endl;
    cout << "0. Salir" << endl;
}

void MostrarObjetivo()
{
    cout << "Agregar duplicados a un set e imprimir los unicos." << endl;
}

void EjecutarEjercicio()
{
    set<int> nums;
    nums.insert(1);
    nums.insert(2);
    nums.insert(2);
    nums.insert(3);
    nums.insert(3);
    nums.insert(3);

    cout << "size(): " << nums.size() << endl;
    for (int n : nums)
    {
        cout << n << endl;
    }
}

int main()
{
    int opcion;
    do
    {
        ImprimirMenu();
        cout << "Introduce una opcion -> ";
        cin >> opcion;
        cout << endl;

        switch (opcion)
        {
            case 1:
                EjecutarEjercicio();
                break;
            case 2:
                MostrarObjetivo();
                break;
            case 0:
                cout << "Saliendo..." << endl;
                break;
            default:
                cout << "Opcion no valida." << endl;
                break;
        }

        cout << endl;
    } while (opcion != 0);
    return 0;
}
