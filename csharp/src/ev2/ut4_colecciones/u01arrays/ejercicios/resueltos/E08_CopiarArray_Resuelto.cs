public class Program
{
    static void Main()
    {
        int opcion;

        do
        {
            ImprimirMenu();
            Console.Write("Introduce una opcion -> ");
            opcion = int.Parse(Console.ReadLine()!);

            switch (opcion)
            {
                case 1:
                    EjecutarEjercicio();
                    break;
                case 2:
                    MostrarObjetivo();
                    break;
                case 0:
                    Console.WriteLine("Saliendo...");
                    break;
                default:
                    Console.WriteLine("Opcion no valida. Intenta de nuevo.");
                    break;
            }

            if (opcion != 0)
            {
                Console.WriteLine();
                Console.WriteLine("Pulsa ENTER para continuar...");
                Console.ReadLine();
                Console.Clear();
            }
        } while (opcion != 0);
    }

    static void ImprimirMenu()
    {
        Console.WriteLine("=== EJERCICIO ===");
        Console.WriteLine("1. Ejecutar solucion");
        Console.WriteLine("2. Ver objetivo");
        Console.WriteLine("0. Salir");
        
    }

    static void MostrarObjetivo()
    {
        Console.WriteLine(@"Copiar {9,3,6} a otro array e imprimir ambos.");
    }

    static void EjecutarEjercicio()
    {
        int[] origen = { 9, 3, 6 };
        int[] destino = new int[origen.Length];
        for (int i = 0; i < origen.Length; i++) destino[i] = origen[i];
        Console.WriteLine("Origen:");
        foreach (int n in origen) Console.WriteLine(n);
        Console.WriteLine("Destino:");
        foreach (int n in destino) Console.WriteLine(n);
    }
}
