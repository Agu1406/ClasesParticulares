using System;
class Program
{
    static void Main()
    {
        string? opcion;
        do
        {
            Console.WriteLine();
            Console.WriteLine("=== E07 Repaso Do While Resuelto ===");
            Console.WriteLine("1. Ejecutar bucle hasta 0");
            Console.WriteLine("0. Salir");
            Console.Write("Elige una opcion: ");
            opcion = Console.ReadLine();
            switch (opcion)
            {
                case "1":
                    int x;
                    do
                    {
                        Console.Write("Numero (0=salir): ");
                        x = int.Parse(Console.ReadLine() ?? "0");
                    } while (x != 0);
                    break;
                case "0":
                    Console.WriteLine("Saliendo...");
                    break;
                default:
                    Console.WriteLine("Opcion no valida.");
                    break;
            }
        } while (opcion != "0");
    }
}
